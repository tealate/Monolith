// Generate the standalone layer engine. Runtime files never call the legacy namespace.
// Values: translation 1000/block, rotation 1000/degree, scale 1000/unit.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const repo=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const root=path.join(repo,'datapack/data/monolith_anim/function');
const legacy=path.join(repo,'datapack/data/monolith/function');
const files=new Map(), objectives=new Set();
const put=(name,lines)=>files.set(name,'# Generated by tools/build-animation-layers.mjs\n'+(Array.isArray(lines)?lines.join('\n'):lines).trim()+'\n');
const obj=n=>(objectives.add(n),n);
const set=(a,n)=>`scoreboard players set @s ${obj(a)} ${n}`;
const op=(a,sign,b)=>`scoreboard players operation @s ${obj(a)} ${sign} ${b.startsWith('#')?b:'@s '+obj(b)}`;
const call=n=>`function monolith_anim:${n}`;
const cond=(condition,cmd)=>`execute ${condition} run ${cmd}`;
const eq=(a,n,cmd)=>cond(`if score @s ${obj(a)} matches ${n}`,cmd);
const valid=(a,r)=>cond(`unless score @s ${obj(a)} matches ${r}`,'return 0');
const channels=['tx','ty','tz','rx','ry','rz','sx','sy','sz'];
const tr=(i,c,k)=>obj(`ml_l${i}${c}${k}`);
const slot=(i,k)=>obj(`ml_l${i}_${k}`);
const prop=c=>({t:'translation',r:'rotation',s:'scale'}[c[0]]+'_'+c[1]);
const easeRewrite=s=>s.replaceAll('monolith:animation/easing/','monolith_anim:easing/').replaceAll('monolith:easing','monolith_anim:easing').replaceAll('ml_a_','ml_le_');
function cloneEasing(dir,prefix='easing'){
  for(const entry of fs.readdirSync(dir,{withFileTypes:true}).sort((a,b)=>a.name.localeCompare(b.name))){
    const target=path.join(dir,entry.name),name=prefix+'/'+entry.name;
    if(entry.isDirectory())cloneEasing(target,name);
    else if(entry.name.endsWith('.mcfunction'))put(name.slice(0,-11),easeRewrite(fs.readFileSync(target,'utf8')));
  }
}
cloneEasing(path.join(legacy,'animation/easing'));
const easeLoad=fs.readFileSync(path.join(legacy,'load.mcfunction'),'utf8').split(/\r?\n/)
  .filter(s=>s.startsWith('scoreboard players set #')||s.startsWith('data modify storage monolith:easing_lut')).map(easeRewrite);
for(const s of files.values())for(const m of s.matchAll(/\bml_le_\w+/g))objectives.add(m[0]);

// Split the product before multiplying: safe for long rotations and path coordinates.
put('math/layer_lerp',[
  op('ml_lm_w','=','ml_lm_b'),op('ml_lm_w','-=','ml_lm_a'),
  op('ml_lm_v','=','ml_lm_w'),op('ml_lm_v','/=','#scale ml_le_tmp0'),op('ml_lm_v','*=','ml_lm_u'),
  op('ml_lm_w','%=','#scale ml_le_tmp0'),op('ml_lm_w','*=','ml_lm_u'),op('ml_lm_w','/=','#scale ml_le_tmp0'),
  op('ml_lm_v','+=','ml_lm_w'),op('ml_lm_v','+=','ml_lm_a')
]);
put('layer/init',[
  'execute if entity @s[tag=monolith_anim.layers] run return 1',
  ...Array.from({length:4},(_,i)=>call(`layer/slot/${i}/clear`)),
  'tag @s add monolith_anim.layers',call('layer/compose')
]);
put('layer/tick',[
  ...Array.from({length:4},(_,i)=>cond(`if score @s ${slot(i,'run')} matches 1 unless score @s ${slot(i,'pause')} matches 1`,call(`layer/slot/${i}/tick`))),
  call('layer/compose')
]);
put('layer/compose',[
  eq('ml_l_dirty',0,'return 1'),set('ml_l_dirty',0),
  ...channels.map(c=>set(`ml_l_${c}`,c[0]==='s'?1000:0)),
  ...Array.from({length:4},(_,i)=>eq(slot(i,'used'),1,call(`layer/slot/${i}/compose`)))
]);

for(let i=0;i<4;i++){
  const dir=`layer/slot/${i}`,pathDir=`path/slot/${i}`;
  put(`${dir}/clear`,[
    set('ml_l_dirty',1),set(slot(i,'used'),0),set(slot(i,'pause'),0),set(slot(i,'path'),0),set(slot(i,'run'),0),
    ...channels.flatMap(c=>[set(tr(i,c,'a'),0),set(tr(i,c,'v'),c[0]==='s'?1000:0)])
  ]);
  put(`${dir}/cancel`,[set(slot(i,'path'),0),set(slot(i,'run'),0),...channels.map(c=>set(tr(i,c,'a'),0))]);
  put(`${dir}/refresh`,[set(slot(i,'run'),0),eq(slot(i,'path'),'1..',set(slot(i,'run'),1)),...channels.map(c=>eq(tr(i,c,'a'),1,set(slot(i,'run'),1)))]);
  put(`${dir}/pause`,[set(slot(i,'pause'),1)]);
  put(`${dir}/resume`,[set(slot(i,'pause'),0)]);
  put(`${dir}/finish`,[
    eq(slot(i,'path'),'1..',call(`${pathDir}/finish`)),
    ...channels.map(c=>eq(tr(i,c,'a'),1,call(`${dir}/${c}/finish`)))
  ]);
  put(`${dir}/compose`,channels.flatMap(c=>c[0]!=='s'?[op(`ml_l_${c}`,'+=',tr(i,c,'v'))]:[
    op(`ml_l_${c}`,'*=',tr(i,c,'v')),op(`ml_l_${c}`,'/=','#unit ml_lm_k'),
    eq(`ml_l_${c}`,'32001..',set(`ml_l_${c}`,32000)),eq(`ml_l_${c}`,'..-32001',set(`ml_l_${c}`,-32000))
  ]));
  put(`${dir}/tick`,[
    eq(slot(i,'path'),'1..',call(`${pathDir}/tick`)),
    ...channels.map(c=>eq(tr(i,c,'a'),1,call(`${dir}/${c}/tick`)))
  ]);
  put(`${dir}/claim`,[set(slot(i,'used'),1),set('ml_l_slot',i),set('ml_l_ok',1)]);
  // Common staging has already been validated: no active state changes before this point.
  put(`${dir}/start`,[
    call(`${dir}/claim`),
    ...channels.map((c,n)=>eq('ml_lc_prop',n,call(`${dir}/${c}/start`))),
    ...['sx','sy','sz'].map(c=>eq('ml_lc_prop',9,call(`${dir}/${c}/start`)))
  ]);
  for(const c of channels){
    const d=`${dir}/${c}`;
    put(`${d}/start`,[
      set('ml_l_dirty',1),
      ...(c[0]==='t'?[set(slot(i,'path'),0)]:[]),set(tr(i,c,'a'),1),set(tr(i,c,'t'),0),
      op(tr(i,c,'d'),'=','ml_lc_d'),op(tr(i,c,'e'),'=','ml_le_easing'),
      op(tr(i,c,'f'),'=','ml_lc_f'),op(tr(i,c,'z'),'=','ml_lc_z'),op(tr(i,c,'v'),'=','ml_lc_f'),
      eq(tr(i,c,'d'),0,call(`${d}/finish`)),call(`${dir}/refresh`)
    ]);
    put(`${d}/finish`,[set('ml_l_dirty',1),op(tr(i,c,'v'),'=',tr(i,c,'z')),set(tr(i,c,'a'),0),call(`${dir}/refresh`)]);
    put(`${d}/tick`,[
      set('ml_l_dirty',1),
      `scoreboard players add @s ${tr(i,c,'t')} 1`,
      cond(`if score @s ${tr(i,c,'t')} >= @s ${tr(i,c,'d')}`,`return run ${call(`${d}/finish`)}`),
      op('ml_le_tmp0','=',tr(i,c,'t')),op('ml_le_tmp0','*=','#scale ml_le_tmp0'),op('ml_le_tmp0','/=',tr(i,c,'d')),
      op('ml_le_easing','=',tr(i,c,'e')),call('easing/dispatch'),
      op('ml_lm_u','=','ml_le_tmp1'),op('ml_lm_a','=',tr(i,c,'f')),op('ml_lm_b','=',tr(i,c,'z')),
      call('math/layer_lerp'),op(tr(i,c,'v'),'=','ml_lm_v')
    ]);
  }
  put(`${pathDir}/start`,[
    set('ml_l_dirty',1),call(`${dir}/claim`),...['tx','ty','tz'].map(c=>set(tr(i,c,'a'),0)),
    op(slot(i,'path'),'=','ml_lc_path'),set(slot(i,'pt'),0),op(slot(i,'pd'),'=','ml_lc_d'),op(slot(i,'pe'),'=','ml_le_easing'),
    op(slot(i,'ph'),'=','ml_lc_h'),
    ...[...'xyz'].flatMap(a=>['s','e','c'].map(p=>op(slot(i,p+a),'=',`ml_lc_${p}${a}`))),
    ...[...'xyz'].map(a=>op(tr(i,'t'+a,'v'),'=',slot(i,'s'+a))),
    eq(slot(i,'pd'),0,call(`${pathDir}/finish`)),call(`${dir}/refresh`)
  ]);
  put(`${pathDir}/finish`,[set('ml_l_dirty',1),...[...'xyz'].map(a=>op(tr(i,'t'+a,'v'),'=',slot(i,'e'+a))),set(slot(i,'path'),0),call(`${dir}/refresh`)]);
  put(`${pathDir}/tick`,[
    set('ml_l_dirty',1),
    `scoreboard players add @s ${slot(i,'pt')} 1`,
    cond(`if score @s ${slot(i,'pt')} >= @s ${slot(i,'pd')}`,`return run ${call(`${pathDir}/finish`)}`),
    op('ml_le_tmp0','=',slot(i,'pt')),op('ml_le_tmp0','*=','#scale ml_le_tmp0'),op('ml_le_tmp0','/=',slot(i,'pd')),
    op('ml_le_easing','=',slot(i,'pe')),call('easing/dispatch'),op('ml_lm_u','=','ml_le_tmp1'),call(`${pathDir}/evaluate`)
  ]);
  put(`${pathDir}/evaluate`,[
    ...[...'xyz'].map(a=>call(`${pathDir}/axis_${a}`)),
    eq(slot(i,'path'),2,call(`${pathDir}/arc`))
  ]);
  for(const a of 'xyz'){
    put(`${pathDir}/axis_${a}`,[
      op('ml_lm_a','=',slot(i,'s'+a)),op('ml_lm_b','=',slot(i,'e'+a)),
      eq(slot(i,'path'),3,op('ml_lm_b','=',slot(i,'c'+a))),
      call('math/layer_lerp'),op(tr(i,'t'+a,'v'),'=','ml_lm_v'),
      eq(slot(i,'path'),3,call(`${pathDir}/bezier_${a}`))
    ]);
    put(`${pathDir}/bezier_${a}`,[
      op('ml_lm_a','=',slot(i,'c'+a)),op('ml_lm_b','=',slot(i,'e'+a)),call('math/layer_lerp'),
      op('ml_lm_a','=',tr(i,'t'+a,'v')),op('ml_lm_b','=','ml_lm_v'),call('math/layer_lerp'),op(tr(i,'t'+a,'v'),'=','ml_lm_v')
    ]);
  }
  put(`${pathDir}/arc`,[
    op('ml_lm_h','=','ml_lm_u'),op('ml_lm_h','*=','ml_lm_u'),op('ml_lm_h','/=','#scale ml_le_tmp0'),
    op('ml_lm_a','=','ml_lm_u'),op('ml_lm_a','-=','ml_lm_h'),op('ml_lm_a','*=','#four ml_lm_k'),
    op('ml_lm_h','=','ml_lm_u'),op('ml_lm_u','=','ml_lm_a'),set('ml_lm_a',0),op('ml_lm_b','=',slot(i,'ph')),
    call('math/layer_lerp'),op(tr(i,'ty','v'),'+=','ml_lm_v'),op('ml_lm_u','=','ml_lm_h')
  ]);
}

put('layer/allocate',[
  call('layer/init'),set('ml_l_ok',0),set('ml_l_slot',-1),
  ...Array.from({length:4},(_,i)=>eq(slot(i,'used'),0,`return run ${call(`layer/slot/${i}/claim`)}`)), 'return 0'
]);
const stageScalar=[
  set('ml_l_ok',0),set('ml_lc_prop',-1),set('ml_le_easing',-1),
  '$function monolith_anim:layer/property/$(property)', '$function monolith_anim:easing/resolve/$(easing)',
  valid('ml_lc_prop','0..9'),valid('ml_le_easing','0..30'),
  '$scoreboard players set @s ml_lc_f $(from)','$scoreboard players set @s ml_lc_z $(to)','$scoreboard players set @s ml_lc_d $(duration)',
  valid('ml_lc_d','0..200000'),
  ...['ml_lc_f','ml_lc_z'].flatMap(f=>[
    cond(`if score @s ml_lc_prop matches 0..2 unless score @s ${f} matches -1000000..1000000`,'return 0'),
    cond(`if score @s ml_lc_prop matches 3..5 unless score @s ${f} matches -3600000..3600000`,'return 0'),
    cond(`if score @s ml_lc_prop matches 6..9 unless score @s ${f} matches -8000..8000`,'return 0')
  ])
];
channels.forEach((c,n)=>put(`layer/property/${prop(c)}`,[set('ml_lc_prop',n)]));
put('layer/property/scale_xyz',[set('ml_lc_prop',9)]);
put('layer/start',[
  ...stageScalar,'$scoreboard players set @s ml_l_slot $(slot)',valid('ml_l_slot','0..3'),call('layer/init'),
  ...Array.from({length:4},(_,i)=>eq('ml_l_slot',i,call(`layer/slot/${i}/start`))),call('layer/compose'),'return 1'
]);
put('layer/start_auto',[
  ...stageScalar,call('layer/allocate'),valid('ml_l_slot','0..3'),
  ...Array.from({length:4},(_,i)=>eq('ml_l_slot',i,call(`layer/slot/${i}/start`))),call('layer/compose'),'return 1'
]);
for(const action of ['cancel','clear','pause','resume','finish'])put(`layer/${action}`,[
  set('ml_l_ok',0),'$scoreboard players set @s ml_l_slot $(slot)',valid('ml_l_slot','0..3'),call('layer/init'),
  ...Array.from({length:4},(_,i)=>eq('ml_l_slot',i,call(`layer/slot/${i}/${action}`))),call('layer/compose'),set('ml_l_ok',1),'return 1'
]);
for(const [name,type] of [['linear',1],['arc',2],['bezier',3]])put(`path/${name}`,[
  `$function monolith_anim:path/start {slot:$(slot),path:${type},sx:$(sx),sy:$(sy),sz:$(sz),ex:$(ex),ey:$(ey),ez:$(ez),cx:${type===3?'$(cx)':0},cy:${type===3?'$(cy)':0},cz:${type===3?'$(cz)':0},height:${type===2?'$(height)':0},duration:$(duration),easing:"$(easing)"}`
]);
put('path/start',[
  set('ml_l_ok',0),set('ml_le_easing',-1),'$function monolith_anim:easing/resolve/$(easing)',valid('ml_le_easing','0..30'),
  '$scoreboard players set @s ml_l_slot $(slot)','$scoreboard players set @s ml_lc_path $(path)',
  '$scoreboard players set @s ml_lc_d $(duration)','$scoreboard players set @s ml_lc_h $(height)',
  valid('ml_l_slot','0..3'),valid('ml_lc_path','1..3'),valid('ml_lc_d','0..200000'),valid('ml_lc_h','-1000000..1000000'),
  ...[...'xyz'].flatMap(a=>['s','e','c'].map(p=>`$scoreboard players set @s ${obj(`ml_lc_${p}${a}`)} $(${p}${a})`)),
  ...[...'xyz'].flatMap(a=>['s','e','c'].map(p=>valid(`ml_lc_${p}${a}`,'-1000000..1000000'))),call('layer/init'),
  ...Array.from({length:4},(_,i)=>eq('ml_l_slot',i,call(`path/slot/${i}/start`))),call('layer/compose'),'return 1'
]);
// Collect macro-only staging objectives too. Maximum name length remains <=16.
for(const s of files.values())for(const m of s.matchAll(/\bml_l\w+/g))objectives.add(m[0]);
objectives.add('ml_lm_k');
for(const n of objectives)if(n.length>16)throw Error('Objective too long: '+n);
put('layer/load',[
  ...[...objectives].sort().map(n=>`scoreboard objectives add ${n} dummy`),...easeLoad,
  'scoreboard players set #unit ml_lm_k 1000','scoreboard players set #four ml_lm_k 4'
]);
for(const [name,text] of files){const target=path.join(root,name+'.mcfunction');fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,text);}
console.log(`Generated ${files.size} standalone layer/easing/path functions (${objectives.size} objectives).`);
