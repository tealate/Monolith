// Deterministic generation of repetitive scoreboard track and path functions.
// Run: node tools/build-transform.mjs. Only owned files in this manifest are written.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../datapack/data/monolith/function');
const files = new Map();
const put = (name, lines) => files.set(name, '# Generated by tools/build-transform.mjs\n' + (Array.isArray(lines) ? lines.join('\n') : lines).trim() + '\n');
const op = (a, sign, b) => `scoreboard players operation @s ${a} ${sign} ${b.startsWith('#') ? b : '@s ' + b}`;
const set = (a, n) => `scoreboard players set @s ${a} ${n}`;
const call = n => `function monolith:animation/${n}`;
const tracks = ['t','r','s'];
const fields = ['elapsed','duration','easing','from','to','property'];
const objectives = new Set(['ml_path_type','ml_space','ml_height','ml_path_u','ml_path_a','ml_path_b','ml_path_v','ml_path_w','ml_path_h','ml_rot_i','ml_rot_j','ml_rot_rem','ml_rot_s0','ml_rot_s1','ml_rot_c0','ml_rot_c1','ml_parent_id','ml_parent_ref','ml_parent_mode','ml_parent_eye','ml_parent_seen','ml_demo_root']);
for (const axis of 'xyz') for (const point of ['start','end','ctrl','out','cfgs','cfge','cfgc']) objectives.add(`ml_${point}_${axis}`);
for (const c of tracks) {
  objectives.add(`ml_${c}_active`);
  for(const f of fields) objectives.add(`ml_${c}_${f}`);
  put(`animation/track/${c}/save`,fields.map(f=>op(`ml_${c}_${f}`,'=',`ml_a_${f}`)));
  put(`animation/track/${c}/load`,fields.map(f=>op(`ml_a_${f}`,'=',`ml_${c}_${f}`)));
  put(`animation/track/${c}/start`,[
    set(`ml_${c}_active`,1), call(`track/${c}/save`),
    op('ml_a_value','=','ml_a_from'),call('adapter/dispatch'),
    `execute if score @s ml_a_duration matches ..0 run function monolith:animation/value/finish`,
    `execute if score @s ml_a_duration matches ..0 run ${set(`ml_${c}_active`,0)}`,
    call(`track/${c}/save`),call('track/refresh')
  ]);
  put(`animation/track/${c}/update`,[
    call(`track/${c}/load`),call('value/update'),call(`track/${c}/save`),
    `execute if score @s ml_a_duration matches ..0 run ${set(`ml_${c}_active`,0)}`
  ]);
  put(`animation/track/${c}/finish`,[call(`track/${c}/load`),call('value/finish'),call(`track/${c}/save`),set(`ml_${c}_active`,0)]);
}
put('animation/track/refresh',[
  'tag @s remove monolith.animating',
  ...tracks.map(c=>`execute if score @s ml_${c}_active matches 1 run tag @s add monolith.animating`)
]);
put('animation/update',[
  '# A missing/unloaded parent freezes all tracks; resume when the same parent returns.',
  'execute if entity @s[tag=monolith.child] unless score @s ml_parent_seen matches 1 run return 0',
  ...tracks.map(c=>`execute if score @s ml_${c}_active matches 1 run function monolith:animation/track/${c}/update`),
  call('track/refresh'), 'data modify entity @s start_interpolation set value 0'
]);
put('animation/cancel', [...tracks.map(c=>set(`ml_${c}_active`,0)),set('ml_a_elapsed',0),set('ml_a_duration',0),'tag @s remove monolith.animating']);
put('animation/finish', [...tracks.map(c=>`execute if score @s ml_${c}_active matches 1 run function monolith:animation/track/${c}/finish`),call('track/refresh')]);
for (const [name,c] of [['translation','t'],['rotation','r'],['scale','s']]) put(`animation/cancel_${name}`,[set(`ml_${c}_active`,0),call('track/refresh')]);
const checkDisplay = 'execute if entity @s[tag=monolith_anim.node] run return 0\nexecute unless entity @s[type=minecraft:block_display] unless entity @s[type=minecraft:item_display] unless entity @s[type=minecraft:text_display] run return 0';
put('animation/start',[
  '# Backward-compatible scalar API; overwrite only the selected transform track.',
  checkDisplay,set('ml_a_property',-1),set('ml_a_easing',-1),
  '$function monolith:animation/adapter/resolve/$(property)',
  '$function monolith:animation/easing/resolve/$(easing)',
  'execute unless score @s ml_a_property matches 0..12 run return 0',
  'execute if score @s ml_a_property matches 9 run return 0',
  'execute unless score @s ml_a_easing matches 0..30 run return 0',
  `execute if entity @s[tag=monolith.child] if score @s ml_a_property matches 7 run ${set('ml_a_property',11)}`,
  `execute if entity @s[tag=monolith.child] if score @s ml_a_property matches 8 run ${set('ml_a_property',10)}`,
  '$scoreboard players set @s ml_a_from $(from)',
  '$scoreboard players set @s ml_a_to $(to)',
  '$scoreboard players set @s ml_a_duration $(duration)',
  '# Documented range prevents scoreboard intermediate overflow.',
  'execute unless score @s ml_a_from matches -1000000..1000000 run return 0',
  'execute unless score @s ml_a_to matches -1000000..1000000 run return 0',
  'execute if score @s ml_a_duration matches 200001.. run return 0',
  set('ml_a_elapsed',0),
  `execute if score @s ml_a_property matches 0..2 run ${set('ml_space',0)}`,
  'execute if score @s ml_a_property matches 0..2 run function monolith:animation/track/t/start',
  'execute if score @s ml_a_property matches 3..6 run function monolith:animation/track/s/start',
  'execute if score @s ml_a_property matches 7..8 run function monolith:animation/track/r/start',
  'execute if score @s ml_a_property matches 10..12 run function monolith:animation/track/r/start'
]);
// Scalar interpolation: floor division and modulo must be Euclidean, like scoreboard.
put('animation/math/lerp',[
  op('ml_path_w','=','ml_path_b'),op('ml_path_w','-=','ml_path_a'),
  op('ml_path_v','=','ml_path_w'),op('ml_path_v','/=','#scale ml_a_tmp0'),op('ml_path_v','*=','ml_path_u'),
  op('ml_path_w','%=','#scale ml_a_tmp0'),op('ml_path_w','*=','ml_path_u'),op('ml_path_w','/=','#scale ml_a_tmp0'),
  op('ml_path_v','+=','ml_path_w'),op('ml_path_v','+=','ml_path_a')
]);
put('animation/value/update',[
  'execute if score @s ml_a_duration matches ..0 run return run function monolith:animation/value/finish',
  'scoreboard players add @s ml_a_elapsed 1',
  'execute if score @s ml_a_elapsed >= @s ml_a_duration run return run function monolith:animation/value/finish',
  op('ml_a_tmp0','=','ml_a_elapsed'),op('ml_a_tmp0','*=','#scale ml_a_tmp0'),op('ml_a_tmp0','/=','ml_a_duration'),
  call('easing/dispatch'),op('ml_path_u','=','ml_a_tmp1'),op('ml_path_a','=','ml_a_from'),op('ml_path_b','=','ml_a_to'),
  call('math/lerp'),op('ml_a_value','=','ml_path_v'),call('adapter/dispatch')
]);
put('animation/value/finish',[op('ml_a_value','=','ml_a_to'),call('adapter/dispatch'),set('ml_a_elapsed',0),set('ml_a_duration',0)]);
// Path configuration uses staging scores so an invalid start leaves the current path intact.
for(const [name,type] of [['linear',0],['arc',1],['bezier',2]]) {
  put(`animation/path/${name}`,[
    `$function monolith:animation/path/start {space:"$(space)",path:${type},sx:$(sx),sy:$(sy),sz:$(sz),ex:$(ex),ey:$(ey),ez:$(ez),cx:${type===2?'$(cx)':0},cy:${type===2?'$(cy)':0},cz:${type===2?'$(cz)':0},height:${type===1?'$(height)':0},duration:$(duration),easing:"$(easing)"}`
  ]);
}
objectives.add('ml_cfg_space');objectives.add('ml_cfg_path');objectives.add('ml_cfg_height');
put('animation/path/start',[
  checkDisplay,set('ml_a_easing',-1),set('ml_cfg_space',-1),
  '$function monolith:animation/easing/resolve/$(easing)',
  '$function monolith:animation/path/space/$(space)',
  'execute unless score @s ml_a_easing matches 0..30 run return 0',
  'execute unless score @s ml_cfg_space matches 0..1 run return 0',
  '$scoreboard players set @s ml_cfg_path $(path)',
  '$scoreboard players set @s ml_cfg_height $(height)',
  '$scoreboard players set @s ml_a_duration $(duration)',
  'execute unless score @s ml_cfg_path matches 0..2 run return 0',
  'execute unless score @s ml_cfg_height matches -100000..100000 run return 0',
  'execute if score @s ml_a_duration matches 200001.. run return 0',
  ...[...'xyz'].flatMap(a=>['s','e','c'].map(p=>`$scoreboard players set @s ml_cfg${p}_${a} $(${p}${a})`)),
  ...[...'xyz'].flatMap(a=>['s','e','c'].map(p=>`execute unless score @s ml_cfg${p}_${a} matches -100000000..100000000 run return 0`)),
  ...[...'xyz'].flatMap(a=>[['start','s'],['end','e'],['ctrl','c']].map(([p,c])=>op(`ml_${p}_${a}`,'=',`ml_cfg${c}_${a}`))),
  op('ml_space','=','ml_cfg_space'),op('ml_path_type','=','ml_cfg_path'),op('ml_height','=','ml_cfg_height'),
  'execute if score @s ml_space matches 1 run data modify entity @s transformation.translation set value [0f,0f,0f]',
  set('ml_a_property',9),set('ml_a_from',0),set('ml_a_to',10000),set('ml_a_elapsed',0),call('track/t/start')
]);
put('animation/path/space/local',[set('ml_cfg_space',0)]);
put('animation/path/space/world',[set('ml_cfg_space',1)]);
put('animation/path/evaluate',[
  '# ml_a_value is eased progress, deliberately not clamped (Back/Elastic overshoot).',
  op('ml_path_u','=','ml_a_value'),
  ...[...'xyz'].map(a=>call(`path/axis_${a}`)),
  `execute if score @s ml_path_type matches 1 run function monolith:animation/path/arc_height`,
  ...[...'xyz'].flatMap((a,i)=>[
    `execute unless score @s ml_space matches 1 store result entity @s transformation.translation[${i}] float 0.001 run scoreboard players get @s ml_out_${a}`,
    `execute if score @s ml_space matches 1 store result entity @s Pos[${i}] double 0.001 run scoreboard players get @s ml_out_${a}`
  ])
]);
for(const a of 'xyz') put(`animation/path/axis_${a}`,[
  op('ml_path_a','=',`ml_start_${a}`),op('ml_path_b','=',`ml_end_${a}`),
  `execute if score @s ml_path_type matches 2 run ${op('ml_path_b','=',`ml_ctrl_${a}`)}`,
  call('math/lerp'),op(`ml_out_${a}`,'=','ml_path_v'),
  `execute if score @s ml_path_type matches 2 run function monolith:animation/path/bezier_${a}`
]);
for(const a of 'xyz') put(`animation/path/bezier_${a}`,[
  op('ml_path_a','=',`ml_ctrl_${a}`),op('ml_path_b','=',`ml_end_${a}`),call('math/lerp'),
  op('ml_path_b','=','ml_path_v'),op('ml_path_a','=',`ml_out_${a}`),call('math/lerp'),op(`ml_out_${a}`,'=','ml_path_v')
]);
put('animation/path/arc_height',[
  // lerp(0, height, 4u(1-u)), arranged to keep products in int32.
  op('ml_path_h','=','ml_path_u'),op('ml_path_h','*=','ml_path_u'),op('ml_path_h','/=','#scale ml_a_tmp0'),
  op('ml_path_a','=','ml_path_u'),op('ml_path_a','-=','ml_path_h'),
  op('ml_path_a','*=','#four ml_a_tmp0'),
  op('ml_path_h','=','ml_path_u'),op('ml_path_u','=','ml_path_a'),set('ml_path_a',0),op('ml_path_b','=','ml_height'),
  call('math/lerp'),op('ml_out_y','+=','ml_path_v'),op('ml_path_u','=','ml_path_h')
]);
// Parent identity is persistent and allocated once. The selected ID is only an immediate API hand-off.
put('animation/parent/select',[
  'scoreboard players set #selected ml_parent_id 0',
  'execute if entity @s[tag=monolith_anim.node] run return 0',
  'execute if entity @s[tag=monolith.child] run return 0',
  'execute unless score @s ml_parent_id matches 1.. run function monolith:animation/parent/allocate',
  'tag @s add monolith.parent',
  'scoreboard players operation #selected ml_parent_id = @s ml_parent_id'
]);
put('animation/parent/allocate',[
  'scoreboard players add #next ml_parent_id 1',
  'scoreboard players operation @s ml_parent_id = #next ml_parent_id'
]);
put('animation/parent/bind',[
  checkDisplay,'execute if entity @s[tag=monolith.parent] run return 0',
  'execute unless score #selected ml_parent_id matches 1.. run return 0',
  'data modify storage monolith:parent_args config set value {mode:"yaw",anchor:"feet"}',
  '$data modify storage monolith:parent_args config merge value {mode:"$(mode)",anchor:"$(anchor)"}',
  'execute unless data storage monolith:parent_args config{mode:"position_only"} unless data storage monolith:parent_args config{mode:"yaw"} unless data storage monolith:parent_args config{mode:"full_rotation"} run return 0',
  'execute unless data storage monolith:parent_args config{anchor:"feet"} unless data storage monolith:parent_args config{anchor:"eyes"} run return 0',
  'scoreboard players operation @s ml_parent_ref = #selected ml_parent_id',
  set('ml_parent_mode',0),set('ml_parent_eye',0),set('ml_parent_seen',0),
  `execute if data storage monolith:parent_args config{mode:"yaw"} run ${set('ml_parent_mode',1)}`,
  `execute if data storage monolith:parent_args config{mode:"full_rotation"} run ${set('ml_parent_mode',2)}`,
  `execute if data storage monolith:parent_args config{anchor:"eyes"} run ${set('ml_parent_eye',1)}`,
  'tag @s add monolith.child',
  '# Persist local rotation ownership so unbind does not switch adapters mid-tween.',
  `execute if score @s ml_r_property matches 7 run ${set('ml_r_property',11)}`,
  `execute if score @s ml_r_property matches 8 run ${set('ml_r_property',10)}`
]);
put('animation/parent/unbind',[
  '# Keep the current entity and model transforms. Active tweens keep running.',
  'tag @s remove monolith.child','scoreboard players reset @s ml_parent_ref',set('ml_parent_seen',0)
]);
put('animation/parent/tick',[
  'scoreboard players set @e[tag=monolith.child] ml_parent_seen 0',
  'execute as @e[tag=monolith.parent] at @s run function monolith:animation/parent/update'
]);
put('animation/parent/update',[
  'scoreboard players operation #current ml_parent_id = @s ml_parent_id',
  // Cache eye position as an execution context before switching executor to the child.
  'execute as @e[tag=monolith.child,scores={ml_parent_eye=0}] if score @s ml_parent_ref = #current ml_parent_id run function monolith:animation/parent/follow',
  'execute anchored eyes positioned ^ ^ ^ as @e[tag=monolith.child,scores={ml_parent_eye=1}] if score @s ml_parent_ref = #current ml_parent_id run function monolith:animation/parent/follow'
]);
put('animation/parent/follow',[
  set('ml_parent_seen',1),
  '# World paths retain world position, but may still inherit parent orientation.',
  'execute unless score @s ml_space matches 1 if score @s ml_parent_mode matches 0 run tp @s ~ ~ ~',
  'execute unless score @s ml_space matches 1 if score @s ml_parent_mode matches 1 run tp @s ~ ~ ~ ~ 0',
  'execute unless score @s ml_space matches 1 if score @s ml_parent_mode matches 2 run tp @s ~ ~ ~ ~ ~',
  'execute if score @s ml_space matches 1 if score @s ml_parent_mode matches 1 positioned as @s run tp @s ~ ~ ~ ~ 0',
  'execute if score @s ml_space matches 1 if score @s ml_parent_mode matches 2 positioned as @s run tp @s ~ ~ ~ ~ ~'
]);
// Local rotation is a single-axis quaternion, sampled each degree with millidegree interpolation.
const rotations = Array.from({length:361},(_,i)=>({s:Math.round(Math.sin(i*Math.PI/360)*10000),c:Math.round(Math.cos(i*Math.PI/360)*10000)}));
put('animation/rotation/prepare',[
  op('ml_rot_i','=','ml_a_value'),op('ml_rot_i','%=','#turn ml_a_tmp0'),
  op('ml_rot_rem','=','ml_rot_i'),op('ml_rot_rem','%=','#degree ml_a_tmp0'),op('ml_rot_i','/=','#degree ml_a_tmp0'),
  op('ml_rot_j','=','ml_rot_i'),'scoreboard players add @s ml_rot_j 1',
  'execute store result storage monolith:rotation_args i int 1 run scoreboard players get @s ml_rot_i',
  'execute store result storage monolith:rotation_args j int 1 run scoreboard players get @s ml_rot_j',
  'function monolith:animation/rotation/read with storage monolith:rotation_args',
  ...['s','c'].flatMap(k=>[
    op(`ml_rot_${k}1`,'-=',`ml_rot_${k}0`),op(`ml_rot_${k}1`,'*=','ml_rot_rem'),op(`ml_rot_${k}1`,'/=','#degree ml_a_tmp0'),op(`ml_rot_${k}0`,'+=',`ml_rot_${k}1`)
  ])
]);
put('animation/rotation/read',[
  ...['s','c'].flatMap(k=>['i','j'].map((i,n)=>`$execute store result score @s ml_rot_${k}${n} run data get storage monolith:rotation_lut values[$(${i})].${k} 1`))
]);
for (const [i,a] of [...'xyz'].entries()) {
  put(`animation/adapter/local_rotation_${a}`,[call('rotation/prepare'),
    '# Assign all quaternion components: never retain a component from the previous axis.',
    ...[0,1,2].filter(j=>j!==i).map(j=>`data modify entity @s transformation.left_rotation[${j}] set value 0f`),
    `execute store result entity @s transformation.left_rotation[${i}] float ${a==='y'?'-':''}0.0001 run scoreboard players get @s ml_rot_s0`,
    'execute store result entity @s transformation.left_rotation[3] float 0.0001 run scoreboard players get @s ml_rot_c0'
  ]);
  put(`animation/adapter/resolve/local_rotation_${a}`,[set('ml_a_property',10+i)]);
}
// Legacy rotation becomes local only for a child; keep the same behavior for unparented demos.
for(const [i,a] of [[0,'y'],[1,'x']]) put(`animation/adapter/rotation_${a}`,[
  `execute if entity @s[tag=monolith.child] run return run function monolith:animation/adapter/local_rotation_${a}`,
  `execute store result entity @s Rotation[${i}] float 0.001 run scoreboard players get @s ml_a_value`
]);
put('animation/track/load',[
  ...[...objectives].sort().map(n=>`scoreboard objectives add ${n} dummy`),
  'scoreboard players add #next ml_parent_id 0',
  ...[['#four',4],['#turn',360000],['#degree',1000]].map(([p,n])=>`scoreboard players set ${p} ml_a_tmp0 ${n}`),
  'data modify storage monolith:rotation_lut values set value '+JSON.stringify(rotations),
  '# One-time migration of running v1 animations; do not reset an existing track on reload.',
  ...['overworld','the_nether','the_end'].map(d=>`execute in minecraft:${d} as @e[tag=monolith.animating] unless score @s ml_t_active matches 0..1 unless score @s ml_r_active matches 0..1 unless score @s ml_s_active matches 0..1 run function monolith:animation/track/migrate`)
]);
put('animation/track/migrate',[
  ...tracks.map(c=>set(`ml_${c}_active`,0)),
  ...[['t','0..2'],['s','3..6'],['r','7..8']].flatMap(([c,r])=>[
    `execute if score @s ml_a_property matches ${r} run function monolith:animation/track/${c}/save`,
    `execute if score @s ml_a_property matches ${r} run ${set(`ml_${c}_active`,1)}`
  ])
]);
put('animation/tick',[
  // Run root motion first to avoid a one-tick parent lag.
  'execute as @e[tag=monolith.sentinel.root] at @s run function monolith:animation/debug/sentinel_root_tick',
  'execute as @e[tag=monolith.debug.boss] at @s run function monolith:animation/debug/boss_tick',
  'execute as @e[tag=monolith.animating,tag=!monolith.child] run function monolith:animation/update',
  call('parent/tick'),
  'execute as @e[tag=monolith.animating,tag=monolith.child] run function monolith:animation/update',
  'execute as @e[tag=monolith.sentinel.child] at @s run function monolith:animation/debug/sentinel_child_tick',
  'execute as @e[tag=monolith.showcase] at @s run function monolith:animation/debug/showcase_tick'
]);
for (const [name, text] of files) {
  const target = path.join(root, name + '.mcfunction');
  fs.mkdirSync(path.dirname(target), {recursive:true}); fs.writeFileSync(target,text);
}
console.log(`Generated ${files.size} transform functions.`);
