// Reproducible in-game fixtures for the transform extension.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../datapack/data/monolith/function/animation/debug');
const files=new Map();
const put=(n,s)=>files.set(n,'# Generated by tools/build-transform-debug.mjs\n'+s.join('\n')+'\n');
const spawn=(x,y,z,fn)=>`execute at @s rotated ~ 0 positioned ^${x} ^${y} ^${z} summon minecraft:block_display run function monolith:animation/debug/${fn}`;
const t=(prop,from,to,duration,easing)=>`function monolith:animation/start {property:"${prop}",from:${from},to:${to},duration:${duration},easing:"${easing}"}`;
const base=(block)=>`data merge entity @s {Tags:["monolith.debug","monolith.debug.transform"],block_state:{Name:"minecraft:${block}"},transformation:{translation:[0f,0f,0f],left_rotation:[0f,0f,0f,1f],right_rotation:[0f,0f,0f,1f],scale:[0.3f,0.3f,0.3f]},brightness:{block:15,sky:15},teleport_duration:1,interpolation_duration:1}`;
put('transform',[
  'function monolith:animation/debug/reset',
  ...['linear','arc','bezier'].map((n,i)=>spawn((i-1)*5,2,8,`fixture_${n}`)),
  'tellraw @s "Local paths: white=Linear, gold=Arc, amethyst=Bezier. All also rotate and scale independently (3 / 5 / 2 seconds)."'
]);
const pathArgs='space:"local",sx:0,sy:0,sz:0,ex:0,ey:0,ez:5000,duration:60,easing:"out_quad"';
for (const [n,b,extra] of [['linear','white_concrete',''],['arc','gold_block',',height:2500'],['bezier','amethyst_block',',cx:3000,cy:3000,cz:2500']]) put(`fixture_${n}`,[
  base(b),`function monolith:animation/path/${n} {${pathArgs}${extra}}`,
  t('local_rotation_y',0,720000,100,'linear'),t('scale_xyz',300,1000,40,'out_back')
]);
put('world',[
  'function monolith:animation/debug/reset',
  spawn(-3,2,8,'fixture_world'),spawn(3,2,8,'fixture_local'),
  'tellraw @s "Both have body yaw=90: white follows world +Z; gold follows local +Z (rotated)."'
]);
put('fixture_world',[
  base('white_concrete'),'data modify entity @s Rotation set value [90f,0f]',
  // data get integer return must scale before storing, otherwise sub-block precision is lost.
  ...[...'xyz'].map((a,i)=>`execute store result storage monolith:debug_world ${a} int 1 run data get entity @s Pos[${i}] 1000`),
  'execute store result score @s ml_out_z run data get storage monolith:debug_world z',
  'scoreboard players add @s ml_out_z 5000',
  'execute store result storage monolith:debug_world ez int 1 run scoreboard players get @s ml_out_z',
  'function monolith:animation/debug/world_start with storage monolith:debug_world',
  t('local_rotation_y',0,360000,100,'linear'),t('scale_xyz',300,1000,40,'out_back')
]);
put('world_start',['$function monolith:animation/path/arc {space:"world",sx:$(x),sy:$(y),sz:$(z),ex:$(x),ey:$(y),ez:$(ez),height:2500,duration:60,easing:"linear"}']);
put('fixture_local',[base('gold_block'),'data modify entity @s Rotation set value [90f,0f]',`function monolith:animation/path/arc {${pathArgs},height:2500}`,t('local_rotation_y',0,360000,100,'linear'),t('scale_xyz',300,1000,40,'out_back')]);
put('player_parent',[
  'function monolith:animation/debug/reset',
  'function monolith:animation/parent/select',
  ...['position_only','yaw','full_rotation'].map(n=>spawn(0,0,0,`fixture_player_${n}`)),
  'tellraw @s "Walk and look around: white=position only (feet); gold=yaw (feet); amethyst=full rotation (eyes). Child tweens finish but parent following continues. Use reset to remove."'
]);
for (const [n,b,x,anchor] of [['position_only','white_concrete',-2500,'feet'],['yaw','gold_block',0,'feet'],['full_rotation','amethyst_block',2500,'eyes']]) put(`fixture_player_${n}`,[
  base(b),`function monolith:animation/parent/bind {mode:"${n}",anchor:"${anchor}"}`,
  `function monolith:animation/path/bezier {space:"local",sx:${x},sy:1000,sz:3000,ex:${x},ey:1800,ez:4500,cx:${x+1500},cy:3500,cz:2000,duration:120,easing:"in_out_sine"}`,
  t('local_rotation_y',0,720000,120,'linear'),t('scale_xyz',300,800,60,'out_back')
]);
put('boss_parent',[
  'function monolith:animation/debug/reset',
  'execute at @s rotated ~ 0 positioned ^0 ^2 ^9 summon minecraft:marker run function monolith:animation/debug/fixture_boss',
  'tellraw @s "BossRoot moves/turns for 10 seconds: core spins, wings extend and scale, crown jumps. Afterward the assembled boss remains. reset removes it."'
]);
put('fixture_boss',[
  'tag @s add monolith.debug','tag @s add monolith.debug.boss',
  'scoreboard players set @s ml_demo_root 0','function monolith:animation/parent/select',
  ...['core','left','right','top'].map(n=>`execute summon minecraft:block_display run function monolith:animation/debug/boss_${n}`)
]);
for (const [n,b,x,y] of [['core','sea_lantern',0,0],['left','gold_block',-2000,0],['right','amethyst_block',2000,0],['top','diamond_block',0,2000]]) put(`boss_${n}`,[
  base(b),'function monolith:animation/parent/bind {mode:"full_rotation",anchor:"feet"}',
  `function monolith:animation/path/arc {space:"local",sx:${x},sy:${y},sz:0,ex:${x*2},ey:${y},ez:0,height:${n==='top'?2500:500},duration:120,easing:"linear"}`,
  t('local_rotation_y',0,n==='core'?720000:360000,160,'linear'),t('scale_xyz',300,n==='core'?1200:700,60,'out_back')
]);
put('boss_tick',[
  'scoreboard players add @s ml_demo_root 1',
  'execute if score @s ml_demo_root matches ..100 run tp @s ~0.025 ~ ~ ~2 ~',
  'execute if score @s ml_demo_root matches 101..200 run tp @s ~-0.025 ~ ~ ~2 ~',
  'execute if score @s ml_demo_root matches 200.. run tag @s remove monolith.debug.boss'
]);
put('cancel_tracks',[
  'execute as @e[tag=monolith.debug.transform] run function monolith:animation/cancel',
  'tellraw @s "Child tweens cancelled at current values; parent following continues."'
]);
put('detach',[
  'execute as @e[tag=monolith.debug.transform] run function monolith:animation/parent/unbind',
  'tellraw @s "Children detached, keeping their last pose. Active local tweens continue from that base."'
]);
put('remove_boss_parent',[
  'kill @e[type=minecraft:marker,tag=monolith.debug,tag=monolith.parent]',
  'tellraw @s "BossRoot removed: its children should freeze. reset removes the children."'
]);
for (const [name,text] of files) { fs.mkdirSync(root,{recursive:true});fs.writeFileSync(path.join(root,name+'.mcfunction'),text); }
console.log(`Generated ${files.size} debug fixtures.`);
