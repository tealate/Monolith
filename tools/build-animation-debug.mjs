// Consumer examples deliberately live in Monolith; the engine never depends on these functions.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../datapack/data/monolith/function/animation/demo');
const files=new Map();
const put=(n,lines)=>files.set(n,'# Generated by tools/build-animation-debug.mjs\n'+lines.join('\n')+'\n');
const a=(property,from,to,duration,easing='linear',slot=0)=>`function monolith_anim:layer/start {slot:${slot},property:"${property}",from:${from},to:${to},duration:${duration},easing:"${easing}"}`;
const at=(time,cmd)=>`execute if score @s ml_seq_time matches ${time} run ${cmd}`;
const base=(tx=0,ty=0,tz=0,s=1000)=>`function monolith_anim:node/base {tx:${tx},ty:${ty},tz:${tz},rx:0,ry:0,rz:0,sx:${s},sy:${s},sz:${s}}`;
const start=id=>`function monolith_anim:sequence/start {id:"monolith:demo/${id}"}`;
const def=(id,duration,slot,priority=10,extra='')=>`function monolith_anim:sequence/define {id:"monolith:demo/${id}",definition:{tick:"monolith:animation/demo/${id}/tick",duration:${duration},priority:${priority},slot:${slot}${extra}}}`;
put('definitions',[def('root',240,0),def('orbit',240,0),def('part',240,0),def('bob',240,1),def('hit',20,2,50,',on_complete:"monolith:animation/demo/hit/cleanup"'),def('recover',40,0,80),def('master',241,-1),def('entrance',20,0)]);
put('hierarchy',[
 'function monolith:animation/demo/reset','function monolith:animation/demo/definitions',
 'execute positioned ^ ^ ^6 summon minecraft:marker run function monolith:animation/demo/create_root',
 'execute as @e[type=minecraft:marker,tag=monolith.anim_demo.root,limit=1] at @s run function monolith:animation/demo/create_children',
 'tellraw @s {text:"Animation hierarchy: Root path + Orbit rotation + Display spin/scale + Bob. Try /function monolith:animation/demo/hit",color:"aqua"}'
]);
put('create_root',['tag @s add monolith.anim_demo','tag @s add monolith.anim_demo.root','function monolith_anim:node/init',base(),start('root')]);
put('create_children',[
 'function monolith_anim:parent/select','execute summon minecraft:marker run function monolith:animation/demo/create_orbit',
 'execute as @e[type=minecraft:marker,tag=monolith.anim_demo.orbit,limit=1] at @s run function monolith:animation/demo/create_parts'
]);
put('create_orbit',['tag @s add monolith.anim_demo','tag @s add monolith.anim_demo.orbit','function monolith_anim:node/init',base(0,1500,0),'function monolith_anim:parent/bind {mode:"full_rotation",anchor:"feet"}',start('orbit')]);
put('create_parts',[
 'function monolith_anim:parent/select',
 ...[-1,1].map((side)=>`execute summon minecraft:block_display run function monolith:animation/demo/create_part {x:${side*2200},block:"minecraft:${side<0?'amethyst_block':'gold_block'}"}`)
]);
put('create_part',[
 'tag @s add monolith.anim_demo','tag @s add monolith.anim_demo.part',
 '$data merge entity @s {block_state:{Name:"$(block)"},transformation:{translation:[0f,0f,0f],scale:[1f,1f,1f],left_rotation:[0f,0f,0f,1f],right_rotation:[0f,0f,0f,1f]}}',
 'function monolith_anim:node/init','$function monolith_anim:node/base {tx:$(x),ty:0,tz:0,rx:0,ry:0,rz:0,sx:600,sy:600,sz:600}',
 'function monolith_anim:parent/bind {mode:"full_rotation",anchor:"feet"}',start('part'),start('bob')
]);
put('root/tick',[
 '# --- 0t : Curve away from the original anchor ---',at(0,'function monolith_anim:path/bezier {slot:0,sx:0,sy:0,sz:0,cx:3000,cy:2000,cz:0,ex:4000,ey:0,ez:2000,duration:120,easing:"in_out_sine"}'),
 '# --- 120t : Return ---',at(120,'function monolith_anim:path/arc {slot:0,sx:4000,sy:0,sz:2000,ex:0,ey:0,ez:0,height:1500,duration:120,easing:"in_out_sine"}')
]);
put('orbit/tick',[at(0,a('rotation_y',0,720000,240)),at(0,a('rotation_z',0,25000,120,'in_out_sine')),at(120,a('rotation_z',25000,0,120,'in_out_sine'))]);
put('part/tick',[
 '# Independent XYZ rotations and scale channels share layer 0.',
 at(0,a('rotation_x',0,360000,240)),at(0,a('rotation_y',0,720000,240)),at(0,a('rotation_z',0,180000,160)),
 at(0,a('scale_y',1000,2500,60,'out_back')),at(60,a('scale_y',2500,1000,60,'in_out_sine')),
 at(120,a('scale_x',1000,1800,60,'out_quad')),at(180,a('scale_x',1800,1000,60,'in_out_sine'))
]);
put('bob/tick',Array.from({length:8},(_,i)=>at(i*30,a('translation_y',i%2?700:0,i%2?0:700,30,'in_out_sine',1))));
put('hit',['execute as @e[tag=monolith.anim_demo.part] at @s run function monolith_anim:sequence/interrupt {id:"monolith:demo/hit",mode:"pause"}']);
put('hit_parallel',['execute as @e[tag=monolith.anim_demo.part] at @s run function monolith_anim:sequence/interrupt {id:"monolith:demo/hit",mode:"parallel"}']);
put('replace',['execute as @e[tag=monolith.anim_demo.part] at @s run function monolith_anim:sequence/interrupt {id:"monolith:demo/recover",mode:"replace"}']);
put('cancel',['execute as @e[tag=monolith.anim_demo.part] at @s run function monolith_anim:sequence/interrupt {id:"monolith:demo/recover",mode:"cancel"}']);
put('hit/tick',[
 '# Layer 2 has its own shake while instance-owned layers 0/1 are paused.',
 at(0,a('translation_x',0,350,4,'out_quad',2)),at(4,a('translation_x',350,-350,4,'linear',2)),at(8,a('translation_x',-350,250,4,'linear',2)),at(12,a('translation_x',250,-150,4,'linear',2)),at(16,a('translation_x',-150,0,4,'out_quad',2)),
 at(0,'particle minecraft:crit ~ ~1 ~ 0.2 0.2 0.2 0.1 12 force'),at(0,'playsound minecraft:block.amethyst_block.hit master @a[distance=..32] ~ ~ ~ 0.6 0.8')
]);
put('hit/cleanup',['function monolith_anim:layer/clear {slot:2}']);
put('recover/tick',[at(0,a('scale_xyz',300,1000,40,'out_back')),at(0,a('rotation_z',-45000,0,40,'out_quart')),at(0,'particle minecraft:happy_villager ~ ~1 ~ 0.4 0.4 0.4 0 12 force')]);
put('children',[
 'function monolith:animation/demo/reset','function monolith:animation/demo/definitions',
 'execute positioned ^ ^ ^5 summon minecraft:block_display run function monolith:animation/demo/create_master'
]);
put('create_master',[
 'tag @s add monolith.anim_demo','tag @s add monolith.anim_demo.part','data merge entity @s {block_state:{Name:"minecraft:sea_lantern"}}','function monolith_anim:node/init',base(0,1000,0),start('master')
]);
put('master/tick',[
 '# --- 0t : Wait for entrance; the sequencer resumes at time 1 exactly once. ---',
 at(0,'function monolith_anim:sequence/child {id:"monolith:demo/entrance",mode:"wait"}'),
 '# --- 1t : Two independent children on separate layers. ---',
 at(1,'function monolith_anim:sequence/child {id:"monolith:demo/part",mode:"parallel"}'),
 at(1,'function monolith_anim:sequence/child {id:"monolith:demo/bob",mode:"parallel"}')
]);
put('entrance/tick',[at(0,a('scale_xyz',100,1000,20,'out_back'))]);
put('player',[
 'function monolith:animation/demo/hierarchy',
 'function monolith_anim:parent/select',
 'execute as @e[tag=monolith.anim_demo.root,limit=1] run function monolith_anim:parent/bind {mode:"full_rotation",anchor:"eyes"}',
 'execute as @e[tag=monolith.anim_demo.root,limit=1] run '+base(0,0,6000)
]);
put('reset',[
 '# This demo owns only these entities. Owner loss lets the engine reclaim its instances on the next tick.',
 'kill @e[tag=monolith.anim_demo]'
]);
for(const [n,text] of files){const target=path.join(root,n+'.mcfunction');fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,text);}
console.log(`Generated ${files.size} Animation consumer demos.`);
