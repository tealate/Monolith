// Reproducible entry point; legacy Transform generator remains separate.
import './build-transform.mjs';
import './build-animation-layers.mjs';
import './build-animation-nodes.mjs';
import './build-animation-sequence.mjs';
import './build-animation-debug.mjs';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const repo=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const root=path.join(repo,'datapack/data/monolith_anim/function');
const write=(name,lines)=>fs.writeFileSync(path.join(root,name+'.mcfunction'),'# Generated by tools/build-animation.mjs\n'+lines.join('\n')+'\n');
write('load',['function monolith_anim:layer/load','function monolith_anim:node/load','function monolith_anim:sequence/load','function #monolith_anim:definitions']);
write('tick',['function #monolith_anim:dimensions']);
write('tick_dimension',['function monolith_anim:sequence/tick','function monolith_anim:node/tick']);
fs.mkdirSync(path.join(root,'dimension'),{recursive:true});
const dimensions=['overworld','the_nether','the_end'];
for(const d of dimensions)write('dimension/'+d,[`execute in minecraft:${d} run function monolith_anim:tick_dimension`]);
const tagRoot=path.join(repo,'datapack/data/monolith_anim/tags/function');fs.mkdirSync(tagRoot,{recursive:true});
fs.writeFileSync(path.join(tagRoot,'dimensions.json'),JSON.stringify({values:dimensions.map(d=>'monolith_anim:dimension/'+d)},null,2)+'\n');
fs.writeFileSync(path.join(tagRoot,'definitions.json'),JSON.stringify({values:[]},null,2)+'\n');
for(const type of ['load','tick']){
 const file=path.join(repo,`datapack/data/minecraft/tags/function/${type}.json`),tag=JSON.parse(fs.readFileSync(file,'utf8'));
 if(!tag.values.includes('monolith_anim:'+type))tag.values.push('monolith_anim:'+type);
 fs.writeFileSync(file,JSON.stringify(tag,null,2)+'\n');
}
console.log('Wired independent monolith_anim load/tick tags.');
